"""One-off correction of «مطاعم رواق» data recorded before ADR-021 (PPS-122, PPS-128).

Every quote in the «مطاعم رواق» demo workspace was generated by docs/gtm/gcc/setup/quotes/gen_quotes*.py
and states «الأسعار شاملة ضريبة القيمة المضافة 15%»: printed prices include 15% VAT. They were
recorded before quotation.prices_include_vat existed, so:

* quotes: prices_include_vat false, line vat_rate empty;
* landed cost: rule v1 rows with VAT 0 (the total is right; the VAT inside it is not shown);
* purchase orders PO-000001…: unit prices are VAT-inclusive with line tax 0, so the last-PO-price
  savings baseline would compare a gross price with the net price of every new order.

This script brings them onto the ADR-021 basis without changing any printed or total amount:

1. A quote is corrected only if it is SAR, not yet flagged, and its lines sum to the stated total
   (±0.01), i.e. the printed line prices are the gross prices. It gets prices_include_vat = true and
   vat_rate 0.15 on every line without one.
2. For each corrected line's current match decision whose latest landed cost is v1, a landed-cost
   v2 row is APPENDED (landed_cost is append-only), recomputed by the application's own rule from
   the v1 row's stored inputs: same total, VAT now derived. valid_from/valid_to are copied (same
   offer, same validity); recorded_at is now.
3. Every SAR purchase-order line in the workspace with tax 0 is corrected. PO-000001…000005 came
   from requests prepared from the quotes above; PO-000006…000009 from requests with no quote link,
   at prices taken from those same quotes. This is safe only because every quote in the workspace
   is VAT-inclusive, so the script stops if step 1 skipped any quote. Unit price becomes net
   (gross / 1.15, 4 dp), tax = gross line total − net line total, so the line total and the order
   total stay exactly as they were. purchase_order.tax_amount (the separate, manually entered
   order-level tax, which the order total does not include) is left as it is, as on new orders.
4. One audit_event row records the correction.

Saving ledger rows (saving_record, purchase_record) are left as they are (owner decision).
«مطاعم سند» is never touched: the script refuses any other tenant.

Default is a dry run: everything happens in one transaction that is rolled back, and every
change is printed. Pass --apply to commit (owner approval required first).

Run from the repo root with the API venv:
    set -a; . ./.env; set +a
    PYTHONPATH=apps/api/src apps/api/.venv/bin/python \
      docs/gtm/gcc/rounds/flow-review-2026-10-28/fixes-pps-122-128/correct_vat_inclusive.py [--apply]
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from decimal import Decimal
from uuid import UUID

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb

from procurepilot_api.modules.landed_cost.rules import (
    RULE_VERSION_V1,
    RULE_VERSION_V2,
    LandedCostInputs,
    MoneyValue,
    compute_landed_cost,
)
from procurepilot_api.modules.orders.vat_split import split_vat_inclusive_line

RAWAQ_TENANT_ID = UUID("938537ad-846d-4cde-b0d3-1ecda1b38a50")  # «مطاعم رواق»
SANAD_TENANT_ID = UUID("61590605-752c-4263-b3a3-97dd89a43232")  # «مطاعم سند»: never touched
VAT_RATE = Decimal("0.15")
TOLERANCE = Decimal("0.01")

QUOTES_SQL = """
select q.id, q.stated_total_amount, s.name as supplier,
       coalesce(sum(ql.quantity * ql.unit_price_amount), 0) as line_sum,
       count(ql.id) as lines,
       count(ql.id) filter (where ql.vat_rate is null) as lines_without_rate
from quotation q
left join supplier s on s.id = q.supplier_id
left join quotation_line ql on ql.quotation_id = q.id
where q.tenant_id = %(tenant)s
  and q.currency = 'SAR'
  and not q.prices_include_vat
  and q.stated_total_amount is not null
group by q.id, s.name
order by q.created_at
"""

LANDED_SQL = """
select distinct on (md.id) md.id as decision_id, lc.*
from current_match_decision md
join landed_cost lc on lc.match_decision_id = md.id
join quotation_line ql on ql.id = md.quotation_line_id
where ql.quotation_id = any(%(quotes)s) and md.tenant_id = %(tenant)s
order by md.id, lc.recorded_at desc, lc.id desc
"""

PO_LINES_SQL = """
select po.id as po_id, po.order_number, po.status, po.total_amount as po_total,
       po.tax_amount as po_tax, pol.id, pol.line_number, pol.description, pol.ordered_quantity,
       pol.unit_price_amount, pol.unit_price_currency, pol.tax_amount, pol.line_total_amount
from purchase_order po
join purchase_order_line pol on pol.purchase_order_id = po.id and pol.tenant_id = po.tenant_id
where po.tenant_id = %(tenant)s
  and po.total_currency = 'SAR'
  and pol.unit_price_currency = 'SAR'
  and pol.tax_amount = 0
order by po.order_number, pol.line_number
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--apply", action="store_true", help="commit (default: dry run)")
    args = parser.parse_args()
    tenant = RAWAQ_TENANT_ID
    if tenant == SANAD_TENANT_ID:
        raise SystemExit("refusing to touch «مطاعم سند»")
    url = os.environ["DATABASE_URL"].replace(":6543/", ":5432/")
    with psycopg.connect(url, prepare_threshold=None, row_factory=dict_row) as conn:
        with conn.transaction() as tx:
            summary = correct(conn, tenant)
            print(json.dumps(summary["counts"], indent=2))
            if not args.apply:
                print("DRY RUN: rolled back, nothing written.")
                raise psycopg.Rollback(tx)
        if args.apply:
            print("APPLIED: committed.")
    return 0


def correct(conn: psycopg.Connection, tenant: UUID) -> dict[str, object]:
    cur = conn.cursor()
    tenant_name = cur.execute("select name from tenant where id = %s", (tenant,)).fetchone()
    if tenant_name is None or tenant_name["name"] != "مطاعم رواق":
        raise SystemExit(f"unexpected tenant for {tenant}: {tenant_name}")

    # 1. Quotes
    print("== Quotes (prices_include_vat → true; empty line vat_rate → 0.15)")
    quote_ids: list[UUID] = []
    skipped = 0
    for q in cur.execute(QUOTES_SQL, {"tenant": tenant}).fetchall():
        gross_lines = abs(Decimal(q["line_sum"]) - Decimal(q["stated_total_amount"])) <= TOLERANCE
        mark = "fix " if gross_lines else "SKIP"
        print(
            f"  {mark} {q['id']} {q['supplier']}: stated {q['stated_total_amount']}, "
            f"lines sum {Decimal(q['line_sum']):.4f}, {q['lines_without_rate']}/{q['lines']} lines "
            "without a rate"
        )
        if not gross_lines:
            skipped += 1
            continue
        quote_ids.append(q["id"])
    lines_rated = 0
    if quote_ids:
        cur.execute(
            "update quotation set prices_include_vat = true where id = any(%s) and tenant_id = %s",
            (quote_ids, tenant),
        )
        cur.execute(
            "update quotation_line set vat_rate = %s "
            "where quotation_id = any(%s) and tenant_id = %s and vat_rate is null",
            (VAT_RATE, quote_ids, tenant),
        )
        lines_rated = cur.rowcount

    # 2. Landed cost v2 rows, appended
    print("== Landed cost (append v2 beside each current decision's v1 row)")
    appended = 0
    for row in cur.execute(LANDED_SQL, {"quotes": quote_ids, "tenant": tenant}).fetchall():
        if row["rule_version"] != RULE_VERSION_V1:
            continue
        raw = row["raw_inputs"]
        currency = row["unit_price_currency"]
        result = compute_landed_cost(
            LandedCostInputs(
                quantity=Decimal(str(raw["quantity"])),
                normalised_base_quantity=Decimal(str(raw["normalised_base_quantity"])),
                base_unit=str(raw["base_unit"]),
                unit_price=MoneyValue(Decimal(str(raw["unit_price"]["amount"])), currency),
                vat_rate=VAT_RATE,
                delivery_fee=MoneyValue(Decimal(str(raw["delivery_fee"]["amount"])), currency),
                discount=MoneyValue(Decimal(str(raw["discount"]["amount"])), currency),
                prices_include_vat=True,
            ),
            rule_version=RULE_VERSION_V2,
        )
        if result.total.amount != Decimal(row["total_amount"]):
            raise SystemExit(f"landed total would change for decision {row['decision_id']}")
        print(
            f"  decision {row['decision_id']}: total {result.total.amount} unchanged, "
            f"VAT {row['vat_amount']} → {result.vat_amount.amount}"
        )
        cur.execute(
            """
            insert into landed_cost (
              tenant_id, quotation_line_id, match_decision_id, quantity, normalised_base_quantity,
              base_unit, unit_price_amount, unit_price_currency, vat_amount, vat_currency,
              delivery_fee_amount, delivery_fee_currency, discount_amount, discount_currency,
              other_charges_amount, other_charges_currency, total_amount, total_currency,
              raw_inputs, rule_version, valid_from, valid_to
            ) values (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
            """,
            (
                tenant,
                row["quotation_line_id"],
                row["decision_id"],
                result.quantity,
                result.normalised_base_quantity,
                result.base_unit,
                result.unit_price.amount,
                currency,
                result.vat_amount.amount,
                currency,
                result.delivery_fee.amount,
                currency,
                result.discount.amount,
                currency,
                result.other_charges.amount,
                currency,
                result.total.amount,
                currency,
                Jsonb(result.raw_inputs),
                RULE_VERSION_V2,
                row["valid_from"],
                row["valid_to"],
            ),
        )
        appended += 1

    # 3. Purchase orders: net + tax, totals unchanged. Every price in this workspace came from a
    # VAT-inclusive quote; if any quote was not gross, PO prices cannot be assumed gross.
    if skipped:
        raise SystemExit(f"{skipped} quote(s) not VAT-inclusive: PO prices cannot be assumed gross")
    print("== Purchase-order lines (unit price → net, tax = gross − net; totals unchanged)")
    order_tax: dict[UUID, Decimal] = {}
    order_meta: dict[UUID, tuple[str, Decimal, Decimal]] = {}
    po_lines = 0
    for line in cur.execute(PO_LINES_SQL, {"tenant": tenant}).fetchall():
        quantity = Decimal(line["ordered_quantity"])
        gross = Decimal(line["unit_price_amount"])
        split = split_vat_inclusive_line(gross, quantity, VAT_RATE)
        if split.line_total != Decimal(line["line_total_amount"]):
            raise SystemExit(f"{line['order_number']} line {line['line_number']}: total would change")
        print(
            f"  {line['order_number']} ({line['status']}) line {line['line_number']} "
            f"{line['description']}: {format(quantity.normalize(), 'f')} × {gross} → net {split.net_unit_price}, "
            f"tax {split.tax}, line total {split.line_total} (was {line['line_total_amount']})"
        )
        cur.execute(
            "update purchase_order_line set unit_price_amount = %s, tax_amount = %s "
            "where id = %s and tenant_id = %s",
            (split.net_unit_price, split.tax, line["id"], tenant),
        )
        order_tax[line["po_id"]] = order_tax.get(line["po_id"], Decimal("0")) + split.tax
        order_meta[line["po_id"]] = (
            line["order_number"],
            Decimal(line["po_total"]),
            Decimal(line["po_tax"]),
        )
        po_lines += 1
    for po_id, tax in order_tax.items():
        number, total, _ = order_meta[po_id]
        print(f"  {number}: line tax {tax}, order total {total} unchanged")

    counts = {
        "quotes_corrected": len(quote_ids),
        "quotes_skipped_not_gross": skipped,
        "quote_lines_rated": lines_rated,
        "landed_cost_v2_rows_appended": appended,
        "purchase_order_lines_corrected": po_lines,
        "purchase_orders_corrected": sorted(meta[0] for meta in order_meta.values()),
    }
    cur.execute(
        "insert into audit_event (tenant_id, actor_email, action, target, outcome) "
        "values (%s, %s, %s, %s, 'success')",
        (
            tenant,
            "claude-orchestrator (owner-approved one-off)",
            "data_correction.vat_inclusive_basis",
            Jsonb({"adr": "ADR-021", "jira": ["PPS-122", "PPS-128"], **counts}),
        ),
    )
    return {"counts": counts}


if __name__ == "__main__":
    sys.exit(main())
