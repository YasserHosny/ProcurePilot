#!/usr/bin/env node
/**
 * Keeps marketing knowledge in step with the product and the company. Sources are listed in config/sources.yaml.
 *   npm run sources:sync                     report changes since the last review (git-clone sources are fast-forwarded)
 *   npm run sources:sync -- --mark-reviewed  after updating knowledge, make the current state the review baseline
 * git-local sources (this repo, the website) are read, never pulled or changed; `fetch: true` only fetches to report
 * how far behind origin the checkout is. Sources marked `optional` are reported as missing, not as failures.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const today = new Date().toISOString().slice(0, 10);
const cfg = YAML.parse(fs.readFileSync(path.join(ROOT, 'config/sources.yaml'), 'utf8'));
const statePath = path.join(ROOT, cfg.state_file);
const state = fs.existsSync(statePath) ? JSON.parse(fs.readFileSync(statePath, 'utf8')) : { reviewed: {}, synced: {} };

const git = (cwd, ...a) => execFileSync('git', a, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
const abs = (p) => path.resolve(ROOT, p);
const sha = (p) => createHash('sha256').update(fs.readFileSync(p)).digest('hex').slice(0, 16);

function filesUnder(base, rels) {
  const out = [];
  const walk = (p) => {
    if (!fs.existsSync(p)) return;
    if (fs.statSync(p).isDirectory()) for (const e of fs.readdirSync(p)) walk(path.join(p, e));
    else out.push(p);
  };
  for (const r of rels) walk(path.join(base, r));
  return out;
}

function copyInto(srcBase, rels, dest) {
  let n = 0;
  for (const f of filesUnder(srcBase, rels)) {
    const to = path.join(dest, path.relative(srcBase, f));
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(f, to);
    n++;
  }
  return n;
}

const report = [`# Source updates`, '', `Generated by \`npm run sources:sync\` on ${today}. Compares each source with the last`,
  'reviewed state in `research/source-state.json`. Changes listed here may make product or company knowledge, claims',
  'or drafts out of date: review them, update `knowledge/` and the product folder, then run',
  '`npm run sources:sync -- --mark-reviewed`.', ''];
const current = {};
let problems = 0;

for (const [id, s] of Object.entries(cfg.sources)) {
  report.push(`## ${id} (${s.kind}, ${s.scope})`, '');
  const base = state.reviewed[id];

  if (s.kind === 'manual') {
    report.push('Check in a browser (never sign in) and log what changed in `research/source-log.md`:', '');
    for (const u of s.urls) report.push(`- ${u}`);
    report.push('');
    continue;
  }

  if (s.kind === 'git-clone' || s.kind === 'git-local') {
    const dir = abs(s.path);
    if (s.optional && !fs.existsSync(dir)) { report.push(`Not available here (${s.path}); skipped.`, ''); continue; }
    try {
      if (s.kind === 'git-clone') {
        if (!fs.existsSync(path.join(dir, '.git'))) {
          fs.mkdirSync(path.dirname(dir), { recursive: true });
          execFileSync('git', ['clone', '--branch', s.branch, s.remote, dir], { stdio: 'inherit' });
        } else {
          if (git(dir, 'status', '--porcelain')) throw new Error('the clone has local changes; it must stay read-only');
          git(dir, 'fetch', 'origin', s.branch);
          git(dir, 'merge', '--ff-only', `origin/${s.branch}`);
        }
      }
      const head = git(dir, 'rev-parse', 'HEAD');
      const headLine = git(dir, 'log', '-1', '--format=%h %cs %s');
      if (s.fetch) {
        try { git(dir, 'fetch', '--quiet', 'origin', s.branch); const behind = git(dir, 'rev-list', '--count', `HEAD..origin/${s.branch}`); if (behind !== '0') report.push(`**${behind} commit(s) on origin/${s.branch} not in this checkout yet: pull first** (git pull), then run the sync again.`, ''); } catch { report.push('Could not fetch origin (offline?); reporting the local checkout.', ''); }
      }
      current[id] = { commit: head, checked_on: today };
      report.push(`HEAD: \`${headLine}\``, '');
      if (s.kind === 'git-local') {
        const dirty = git(dir, 'status', '--porcelain', '--', ...s.watch);
        if (dirty) report.push(`Uncommitted changes in watched paths (not yet in HEAD):`, '', '```', dirty, '```', '');
      }
      if (!base?.commit) report.push('No review baseline yet: everything counts as new. Run with `--mark-reviewed` after the first review.', '');
      else if (base.commit === head) report.push(`No new commits since the review on ${base.reviewed_on}.`, '');
      else {
        const log = git(dir, 'log', '--format=- `%h` %cs %s', `${base.commit}..${head}`, '--', ...s.watch);
        const files = git(dir, 'diff', '--name-status', base.commit, head, '--', ...s.watch);
        report.push(`Since the review on ${base.reviewed_on} (\`${base.commit.slice(0, 7)}\`):`, '',
          log || '- no commits touched the watched paths', '', 'Changed files in watched paths:', '', '```', files || '(none)', '```', '');
      }
      if (s.mirror) {
        const to = abs(s.mirror.to);
        const videoDir = path.join(to, 'video-cuts-latest');
        const withVideo = args.has('--with-video') && s.mirror.video;
        // Recreate the docs mirror; keep the (large) video cuts unless they are being refreshed.
        if (fs.existsSync(to)) {
          for (const e of fs.readdirSync(to)) {
            if (e === 'video-cuts-latest' && !withVideo) continue;
            fs.rmSync(path.join(to, e), { recursive: true, force: true });
          }
        }
        let n = copyInto(dir, s.mirror.paths, to);
        if (withVideo) {
          n += copyInto(dir, s.mirror.video, videoDir);
          fs.writeFileSync(path.join(videoDir, 'VIDEO.md'), `# Latest demo cuts (generated)\n\nCopied from \`${headLine}\` on ${today}. Not approved for marketing use until recorded in \`ProcurePilot/demo-video/VERSIONS.md\`.\n`);
        }
        fs.writeFileSync(path.join(to, 'MIRROR.md'), [
          '# Mirror of the product repository (generated, read-only)', '',
          `Copied from ${s.remote} at \`${headLine}\` on ${today} by \`npm run sources:sync\`.`,
          'Do not edit: the next sync deletes and recreates this folder. Edit in the product repo, or write marketing',
          'versions elsewhere in the product folder. Links inside these files point to paths in the product repo.', '',
          `Files copied this sync: ${n}.${withVideo ? ' Includes the latest video cuts.' : ' Video cuts in `video-cuts-latest/` (if present) are from an earlier `--with-video` sync; see its VIDEO.md.'}`, '',
          'This is product-team material. It is evidence for marketing knowledge, not approved marketing copy.', ''].join('\n'));
        report.push(`Mirror refreshed: \`${s.mirror.to}/\` (${n} files).`, '');
      }
    } catch (e) {
      problems++;
      report.push(`**Could not read:** ${String(e.message).split('\n')[0]}`, '');
    }
    continue;
  }

  if (s.kind === 'folder') {
    const dir = abs(s.path);
    if (!fs.existsSync(dir)) { if (!s.optional) problems++; report.push(s.optional ? `Not available here (${s.path}); skipped.` : `**Missing:** ${s.path}`, ''); continue; }
    const hashes = Object.fromEntries(filesUnder(dir, s.watch).map((f) => [path.relative(dir, f).split(path.sep).join('/'), sha(f)]));
    current[id] = { hashes, checked_on: today };
    if (!base?.hashes) report.push(`${Object.keys(hashes).length} files hashed. No review baseline yet.`, '');
    else {
      const changed = Object.keys(hashes).filter((f) => base.hashes[f] && base.hashes[f] !== hashes[f]);
      const added = Object.keys(hashes).filter((f) => !base.hashes[f]);
      const removed = Object.keys(base.hashes).filter((f) => !hashes[f]);
      if (!changed.length && !added.length && !removed.length) report.push(`No changes since the review on ${base.reviewed_on}.`, '');
      for (const [label, list] of [['Changed', changed], ['Added', added], ['Removed', removed]]) {
        if (list.length) report.push(`${label}:`, '', ...list.map((f) => `- \`${f}\``), '');
      }
    }
  }
}

state.synced = current;
if (args.has('--mark-reviewed')) {
  for (const [id, c] of Object.entries(current)) state.reviewed[id] = { ...c, reviewed_on: today };
  report.push(`Review baseline moved to this state (${today}).`, '');
}
fs.mkdirSync(path.dirname(statePath), { recursive: true });
fs.writeFileSync(statePath, JSON.stringify(state, null, 2) + '\n');
const reportPath = path.join(ROOT, cfg.report_file);
fs.mkdirSync(path.dirname(reportPath), { recursive: true });
fs.writeFileSync(reportPath, report.join('\n'));
console.log(report.join('\n'));
console.log(`Report: ${cfg.report_file}`);
process.exit(problems ? 1 : 0);
